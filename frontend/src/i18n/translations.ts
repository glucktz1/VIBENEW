// Translate a Home section title using its stable id (backend titles are English/Swahili mixed).
export function sectionTitleKey(id: string): string | null {
  const map: Record<string, string> = {
    trending: "home.trending",
    new: "home.newReleases",
    artists: "home.artists",
    recent: "home.jumpBackIn",
    recommended: "home.madeForYou",
    pick_week: "home.pickOfWeek",
    recently_added: "home.recentlyAdded",
  };
  return map[id] || null;
}
